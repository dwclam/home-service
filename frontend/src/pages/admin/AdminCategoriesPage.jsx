import { useState, useEffect, useMemo } from 'react'
import { useForm, useWatch } from 'react-hook-form'
import { zodResolver } from '@hookform/resolvers/zod'
import toast from 'react-hot-toast'
import {
  Layers,
  Search,
  Plus,
  Edit2,
  CheckCircle2,
  MinusCircle,
  Eye,
  EyeOff,
  Zap,
  Droplets,
  Sparkles,
  Hammer,
  PawPrint,
  GraduationCap,
  Wrench,
  Shield,
  Home,
  Paintbrush,
  Scissors,
  Compass,
  Briefcase,
  Truck,
  RotateCw,
  X,
} from 'lucide-react'

import { categorySchema, slugifyVietnamese } from '../../features/admin/categorySchemas'
import {
  getAdminCategories,
  createAdminCategory,
  updateAdminCategory,
  toggleAdminCategoryActive,
} from '../../features/admin/categoryApi'
import { Button } from '../../components/ui/Button'
import { Input } from '../../components/ui/Input'
import { FormField } from '../../components/ui/FormField'
import { StatusText } from '../../components/ui/StatusText'

// Bản đồ icon trực quan
const ICON_COMPONENTS = {
  Zap,
  Droplets,
  Sparkles,
  Hammer,
  PawPrint,
  GraduationCap,
  Wrench,
  Shield,
  Home,
  Paintbrush,
  Scissors,
  Compass,
  Briefcase,
  Truck,
}

const AVAILABLE_ICONS = Object.keys(ICON_COMPONENTS)

export const AdminCategoriesPage = () => {
  const [categories, setCategories] = useState([])
  const [isLoading, setIsLoading] = useState(true)
  const [searchTerm, setSearchTerm] = useState('')
  const [statusFilter, setStatusFilter] = useState('ALL') // ALL, ACTIVE, INACTIVE

  // State Modal
  const [modalOpen, setModalOpen] = useState(false)
  const [editingCategory, setEditingCategory] = useState(null)
  const [slugAutoGenerated, setSlugAutoGenerated] = useState(true)

  // Khởi tạo Form React Hook Form
  const {
    register,
    handleSubmit,
    reset,
    setValue,
    control,
    formState: { errors, isSubmitting },
  } = useForm({
    resolver: zodResolver(categorySchema),
    defaultValues: {
      name: '',
      slug: '',
      description: '',
      iconName: 'Zap',
      sortOrder: 0,
      parentId: '',
    },
    mode: 'onTouched',
  })

  const currentIconName = useWatch({ control, name: 'iconName', defaultValue: 'Zap' })

  // Tải danh sách danh mục (khi bấm nút Làm mới)
  const loadCategories = async () => {
    setIsLoading(true)
    try {
      const data = await getAdminCategories()
      setCategories(data || [])
    } catch {
      toast.error('Không thể tải danh sách danh mục.')
    } finally {
      setIsLoading(false)
    }
  }

  useEffect(() => {
    let isMounted = true
    getAdminCategories()
      .then((data) => {
        if (isMounted) setCategories(data || [])
      })
      .catch(() => {
        toast.error('Không thể tải danh sách danh mục.')
      })
      .finally(() => {
        if (isMounted) setIsLoading(false)
      })

    return () => {
      isMounted = false
    }
  }, [])

  // Đóng Modal bằng phím Escape khi không đang gửi form
  useEffect(() => {
    if (!modalOpen) return

    const handleKeyDown = (event) => {
      if (event.key === 'Escape' && !isSubmitting) {
        setModalOpen(false)
      }
    }

    document.addEventListener('keydown', handleKeyDown)
    return () => document.removeEventListener('keydown', handleKeyDown)
  }, [modalOpen, isSubmitting])

  // Mở modal tạo mới
  const handleOpenCreateModal = () => {
    setEditingCategory(null)
    setSlugAutoGenerated(true)
    reset({
      name: '',
      slug: '',
      description: '',
      iconName: 'Zap',
      sortOrder: categories.length + 1,
      parentId: '',
    })
    setModalOpen(true)
  }

  // Mở modal chỉnh sửa
  const handleOpenEditModal = (cat) => {
    setEditingCategory(cat)
    setSlugAutoGenerated(false)
    reset({
      name: cat.name,
      slug: cat.slug,
      description: cat.description || '',
      iconName: cat.iconName || 'Zap',
      sortOrder: cat.sortOrder ?? 0,
      parentId: cat.parentId ? String(cat.parentId) : '',
    })
    setModalOpen(true)
  }

  // Tự động sinh slug khi gõ name (ở chế độ tạo mới)
  const handleNameChange = (e) => {
    const newName = e.target.value
    setValue('name', newName, { shouldValidate: true })
    if (!editingCategory && slugAutoGenerated) {
      const autoSlug = slugifyVietnamese(newName)
      setValue('slug', autoSlug, { shouldValidate: true })
    }
  }

  // Xử lý nộp form tạo mới / sửa
  const onSubmit = async (values) => {
    const payload = {
      ...values,
      parentId: values.parentId ? Number(values.parentId) : null,
    }

    try {
      if (editingCategory) {
        await updateAdminCategory(editingCategory.id, payload)
        toast.success(`Cập nhật danh mục "${values.name}" thành công!`)
      } else {
        await createAdminCategory(payload)
        toast.success(`Thêm mới danh mục "${values.name}" thành công!`)
      }
      setModalOpen(false)
      loadCategories()
    } catch (error) {
      const errorData = error.response?.data
      toast.error(errorData?.message || 'Có lỗi xảy ra khi lưu danh mục.')
    }
  }

  // Bật/tắt trạng thái active
  const handleToggleActive = async (cat) => {
    const nextActive = !cat.active
    try {
      await toggleAdminCategoryActive(cat.id, nextActive)
      toast.success(
        nextActive
          ? `Đã kích hoạt hiển thị danh mục "${cat.name}".`
          : `Đã tạm ẩn danh mục "${cat.name}".`
      )
      setCategories((prev) =>
        prev.map((item) =>
          item.id === cat.id ? { ...item, active: nextActive } : item
        )
      )
    } catch {
      toast.error('Không thể thay đổi trạng thái danh mục.')
    }
  }

  // Thống kê nhanh dùng cho nút lọc trạng thái
  const stats = useMemo(() => {
    const total = categories.length
    const active = categories.filter((c) => c.active).length
    const inactive = total - active
    return { total, active, inactive }
  }, [categories])

  // Map tra cứu danh mục cha theo id
  const categoryById = useMemo(() => {
    return new Map(categories.map((c) => [c.id, c]))
  }, [categories])

  // Lọc danh mục theo tìm kiếm và trạng thái
  const filteredCategories = useMemo(() => {
    const query = searchTerm.trim().toLowerCase()
    return categories.filter((cat) => {
      const matchSearch =
        !query ||
        cat.name.toLowerCase().includes(query) ||
        cat.slug.toLowerCase().includes(query)

      if (!matchSearch) return false

      if (statusFilter === 'ACTIVE') return cat.active
      if (statusFilter === 'INACTIVE') return !cat.active
      return true
    })
  }, [categories, searchTerm, statusFilter])

  // Sắp xếp danh mục theo đúng phân cấp Cha -> Con (nếu cha không khớp bộ lọc, con vẫn hiển thị ở cấp gốc)
  const orderedCategories = useMemo(() => {
    const sortByOrder = (a, b) => {
      const orderDiff = (a.sortOrder ?? 0) - (b.sortOrder ?? 0)
      if (orderDiff !== 0) return orderDiff
      return (a.id ?? 0) - (b.id ?? 0)
    }

    const visibleIds = new Set(filteredCategories.map((c) => c.id))
    const childrenMap = new Map()
    const roots = []

    filteredCategories.forEach((cat) => {
      if (cat.parentId && visibleIds.has(cat.parentId)) {
        const list = childrenMap.get(cat.parentId) || []
        list.push(cat)
        childrenMap.set(cat.parentId, list)
      } else {
        roots.push(cat)
      }
    })

    roots.sort(sortByOrder)
    childrenMap.forEach((list) => list.sort(sortByOrder))

    const result = []
    const visited = new Set()

    const traverse = (node, depth) => {
      if (visited.has(node.id)) return
      visited.add(node.id)
      result.push({ category: node, depth })
      const children = childrenMap.get(node.id) || []
      children.forEach((child) => traverse(child, depth + 1))
    }

    roots.forEach((root) => traverse(root, 0))

    filteredCategories.forEach((cat) => {
      if (!visited.has(cat.id)) {
        result.push({ category: cat, depth: 0 })
      }
    })

    return result
  }, [filteredCategories])

  // Render Icon linh hoạt
  const renderIcon = (iconName, className = 'w-4 h-4') => {
    const IconComponent = ICON_COMPONENTS[iconName] || Layers
    return <IconComponent className={className} aria-hidden="true" />
  }

  const filterTabs = [
    { key: 'ALL', label: `Tất cả (${stats.total})` },
    { key: 'ACTIVE', label: `Hoạt động (${stats.active})` },
    { key: 'INACTIVE', label: `Tạm ẩn (${stats.inactive})` },
  ]

  return (
    <>
      <div className="space-y-6 font-sans">
        {/* Page Header */}
        <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4">
          <h1 className="text-2xl font-display font-bold text-ink">
            Quản Lý Danh Mục Dịch Vụ
          </h1>

          <div className="flex items-center gap-2.5">
            <Button
              type="button"
              variant="secondary"
              size="md"
              onClick={loadCategories}
              isLoading={isLoading}
              leftIcon={<RotateCw className="w-4 h-4" />}
            >
              Làm mới
            </Button>
            <Button
              type="button"
              variant="primary"
              size="md"
              onClick={handleOpenCreateModal}
              leftIcon={<Plus className="w-4 h-4" />}
            >
              Thêm danh mục
            </Button>
          </div>
        </div>

        {/* Filter & Search Bar */}
        <div className="bg-white p-4 rounded-md border border-neutral-200 shadow-xs flex flex-col sm:flex-row items-center justify-between gap-3">
          <div className="w-full sm:w-80">
            <Input
              placeholder="Tìm theo tên hoặc slug..."
              value={searchTerm}
              onChange={(e) => setSearchTerm(e.target.value)}
              leftIcon={<Search className="w-4 h-4 text-neutral-400" />}
            />
          </div>

          {/* Filter Tabs */}
          <div className="flex flex-wrap items-center gap-1.5 w-full sm:w-auto">
            {filterTabs.map((tab) => (
              <button
                key={tab.key}
                type="button"
                onClick={() => setStatusFilter(tab.key)}
                className={`px-3 py-1.5 rounded-md text-xs tabular-nums transition-colors cursor-pointer outline-none focus-visible:ring-2 focus-visible:ring-primary-500/20 ${
                  statusFilter === tab.key
                    ? 'bg-primary-50 text-primary-700 font-semibold'
                    : 'font-medium text-neutral-600 hover:bg-neutral-100'
                }`}
              >
                {tab.label}
              </button>
            ))}
          </div>
        </div>

        {/* Categories Table */}
        <div className="bg-white rounded-md border border-neutral-200 shadow-xs overflow-hidden">
          <div className="overflow-x-auto">
            <table className="w-full text-left border-collapse">
              <thead>
                <tr className="border-b border-neutral-200 bg-neutral-50/70 text-neutral-500 text-xs font-semibold uppercase tracking-wider">
                  <th className="py-3 px-4 w-20 text-center">Thứ tự</th>
                  <th className="py-3 px-4">Tên danh mục</th>
                  <th className="py-3 px-4">Slug</th>
                  <th className="py-3 px-4">Danh mục cha</th>
                  <th className="py-3 px-4">Trạng thái</th>
                  <th className="py-3 px-4 text-right">Thao tác</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-neutral-100 text-sm">
                {orderedCategories.length === 0 ? (
                  <tr>
                    <td colSpan={6} className="py-10 text-center text-neutral-400">
                      Không tìm thấy danh mục phù hợp.
                    </td>
                  </tr>
                ) : (
                  orderedCategories.map(({ category: cat, depth }) => {
                    const parent = cat.parentId ? categoryById.get(cat.parentId) : null
                    return (
                      <tr
                        key={cat.id}
                        className="hover:bg-neutral-50/60 transition-colors"
                      >
                        <td className="py-3 px-4 text-center text-xs text-neutral-500 tabular-nums">
                          {cat.sortOrder ?? 0}
                        </td>

                        <td className="py-3 px-4">
                          <div
                            className={`flex items-center gap-2.5 ${depth > 0 ? 'pl-6' : ''}`}
                          >
                            {depth > 0 && (
                              <span
                                aria-hidden="true"
                                className="w-2.5 h-2.5 border-l border-b border-neutral-300 rounded-bl-[2px] -mt-1.5 shrink-0"
                              />
                            )}
                            {renderIcon(cat.iconName, 'w-4 h-4 text-neutral-400 shrink-0')}
                            <div className="min-w-0">
                              <p
                                className={
                                  depth > 0
                                    ? 'font-medium text-neutral-700'
                                    : 'font-semibold text-ink'
                                }
                              >
                                {cat.name}
                              </p>
                              {cat.description && (
                                <p className="text-xs text-neutral-500 line-clamp-1 max-w-xs">
                                  {cat.description}
                                </p>
                              )}
                            </div>
                          </div>
                        </td>

                        <td className="py-3 px-4">
                          <span className="text-xs text-neutral-500">
                            {cat.slug}
                          </span>
                        </td>

                        <td className="py-3 px-4 text-xs">
                          {parent ? (
                            <span className="text-neutral-700 font-medium">
                              {parent.name}
                            </span>
                          ) : (
                            <span className="text-neutral-400">Danh mục gốc</span>
                          )}
                        </td>

                        <td className="py-3 px-4">
                          {cat.active ? (
                            <StatusText
                              icon={CheckCircle2}
                              label="Hoạt động"
                              tone="success"
                            />
                          ) : (
                            <StatusText
                              icon={MinusCircle}
                              label="Tạm ẩn"
                              tone="neutral"
                            />
                          )}
                        </td>

                        <td className="py-3 px-4 text-right">
                          <div className="inline-flex items-center gap-1.5">
                            {/* Toggle Active Button */}
                            <button
                              type="button"
                              onClick={() => handleToggleActive(cat)}
                              title={cat.active ? 'Tạm ẩn danh mục' : 'Kích hoạt danh mục'}
                              aria-label={
                                cat.active
                                  ? `Tạm ẩn danh mục ${cat.name}`
                                  : `Kích hoạt danh mục ${cat.name}`
                              }
                              className={`p-1.5 rounded-md border text-xs transition-colors cursor-pointer outline-none focus-visible:ring-2 focus-visible:ring-primary-500/20 ${
                                cat.active
                                  ? 'border-neutral-200 text-neutral-500 hover:bg-neutral-100'
                                  : 'border-emerald-200 bg-emerald-50 text-emerald-600 hover:bg-emerald-100'
                              }`}
                            >
                              {cat.active ? (
                                <EyeOff className="w-3.5 h-3.5" />
                              ) : (
                                <Eye className="w-3.5 h-3.5" />
                              )}
                            </button>

                            {/* Edit Button */}
                            <button
                              type="button"
                              onClick={() => handleOpenEditModal(cat)}
                              title="Chỉnh sửa danh mục"
                              aria-label={`Chỉnh sửa danh mục ${cat.name}`}
                              className="p-1.5 rounded-md border border-neutral-200 text-neutral-700 hover:bg-neutral-100 hover:text-primary-600 transition-colors cursor-pointer outline-none focus-visible:ring-2 focus-visible:ring-primary-500/20"
                            >
                              <Edit2 className="w-3.5 h-3.5" />
                            </button>
                          </div>
                        </td>
                      </tr>
                    )
                  })
                )}
              </tbody>
            </table>
          </div>
        </div>
      </div>

      {/* Modal Tạo mới & Chỉnh sửa Danh mục */}
      {modalOpen && (
        <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/50 backdrop-blur-xs">
          <div className="bg-white rounded-md shadow-xl border border-neutral-200 w-full max-w-lg overflow-hidden animate-in fade-in duration-150">
            {/* Modal Header */}
            <div className="flex items-center justify-between px-6 py-4 border-b border-neutral-200">
              <h2 className="font-display font-bold text-lg text-ink">
                {editingCategory ? 'Chỉnh Sửa Danh Mục' : 'Thêm Mới Danh Mục'}
              </h2>
              <button
                type="button"
                disabled={isSubmitting}
                onClick={() => setModalOpen(false)}
                aria-label="Đóng cửa sổ"
                className="text-neutral-400 hover:text-ink cursor-pointer disabled:opacity-50 outline-none focus-visible:ring-2 focus-visible:ring-primary-500/20 rounded"
              >
                <X className="w-5 h-5" />
              </button>
            </div>

            {/* Modal Form */}
            <form onSubmit={handleSubmit(onSubmit)} className="p-6 space-y-4" noValidate>
              {/* Tên danh mục */}
              <FormField
                label="Tên danh mục"
                htmlFor="name"
                required
                error={errors.name?.message}
              >
                <Input
                  {...register('name')}
                  onChange={handleNameChange}
                  placeholder="Ví dụ: Sửa chữa điện lạnh"
                />
              </FormField>

              {/* Slug định danh */}
              <FormField
                label="Slug định danh"
                htmlFor="slug"
                required
                error={errors.slug?.message}
              >
                <Input
                  {...register('slug')}
                  onChange={(e) => {
                    setSlugAutoGenerated(false)
                    setValue('slug', e.target.value, { shouldValidate: true })
                  }}
                  placeholder="sua-chua-dien-lanh"
                />
              </FormField>

              {/* Hàng 2 cột: Thứ tự sắp xếp & Danh mục cha */}
              <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
                <FormField
                  label="Thứ tự sắp xếp"
                  htmlFor="sortOrder"
                  error={errors.sortOrder?.message}
                >
                  <Input
                    {...register('sortOrder')}
                    type="number"
                    min={0}
                    placeholder="0"
                  />
                </FormField>

                <FormField
                  label="Danh mục cha (nếu có)"
                  htmlFor="parentId"
                  error={errors.parentId?.message}
                >
                  <select
                    {...register('parentId')}
                    id="parentId"
                    className="w-full h-10 px-3 text-[14px] font-sans text-ink bg-white rounded-md border border-neutral-200 outline-none focus:border-primary-500 focus:ring-2 focus:ring-primary-500/20"
                  >
                    <option value="">Không có (Danh mục gốc cấp 1)</option>
                    {categories
                      .filter((c) => !editingCategory || c.id !== editingCategory.id)
                      .map((c) => (
                        <option key={c.id} value={c.id}>
                          {c.name}
                        </option>
                      ))}
                  </select>
                </FormField>
              </div>

              {/* Bộ chọn Icon trực quan */}
              <div>
                <label className="block text-sm font-medium text-ink mb-1.5">
                  Chọn biểu tượng (Icon)
                </label>
                <div className="grid grid-cols-7 gap-2 p-2 bg-neutral-50 rounded-md border border-neutral-200 max-h-36 overflow-y-auto">
                  {AVAILABLE_ICONS.map((iconKey) => {
                    const isSelected = currentIconName === iconKey
                    return (
                      <button
                        key={iconKey}
                        type="button"
                        onClick={() => setValue('iconName', iconKey)}
                        className={`p-2 rounded-md flex flex-col items-center justify-center transition-colors cursor-pointer ${
                          isSelected
                            ? 'bg-primary-500 text-white shadow-xs'
                            : 'bg-white text-neutral-600 hover:bg-neutral-100 border border-neutral-200'
                        }`}
                        title={iconKey}
                        aria-label={`Chọn biểu tượng ${iconKey}`}
                      >
                        {renderIcon(iconKey, 'w-4 h-4')}
                      </button>
                    )
                  })}
                </div>
              </div>

              {/* Mô tả */}
              <FormField
                label="Mô tả dịch vụ"
                htmlFor="description"
                error={errors.description?.message}
              >
                <textarea
                  {...register('description')}
                  id="description"
                  rows={3}
                  placeholder="Mô tả tóm tắt dịch vụ thuộc danh mục này..."
                  className="w-full rounded-md border border-neutral-300 px-3.5 py-2.5 text-sm font-sans text-ink outline-none focus:border-primary-500 focus:ring-2 focus:ring-primary-500/20"
                />
              </FormField>

              {/* Modal Actions */}
              <div className="flex items-center justify-end gap-3 pt-3 border-t border-neutral-100">
                <Button
                  type="button"
                  variant="secondary"
                  size="md"
                  disabled={isSubmitting}
                  onClick={() => setModalOpen(false)}
                >
                  Hủy bỏ
                </Button>
                <Button
                  type="submit"
                  variant="primary"
                  size="md"
                  isLoading={isSubmitting}
                >
                  {editingCategory ? 'Lưu thay đổi' : 'Tạo danh mục'}
                </Button>
              </div>
            </form>
          </div>
        </div>
      )}
    </>
  )
}

export default AdminCategoriesPage
